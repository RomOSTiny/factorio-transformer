GLYPHS = _RAW
W, H = 5, 7


def pixels(ch):
    """Lit pixel indices p = row * 5 + col."""
    rows = GLYPHS[ch]
    assert len(rows) == H and all(len(r) == W for r in rows), ch
    return [r * W + c for r in range(H) for c in range(W) if rows[r][c] == "#"]


def codes(ch):
    """(code1, code2): bit p+1 of code1 for pixels 0..19 (rows 0-3), bit p-19 of code2 for 20..34."""
    c1 = c2 = 0
    for p in pixels(ch):
        if p < 20:
            c1 |= 1 << (p + 1)
        else:
            c2 |= 1 << (p - 19)
    return c1, c2


def shift(p):
    return p + 1 if p < 20 else p - 19


